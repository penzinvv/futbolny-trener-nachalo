-- Version 2.8.20: online career record snapshots.
-- Additive only: preserve existing online_coach_ratings and all career data.
alter table public.online_coach_ratings
  add column if not exists coach_title text,
  add column if not exists coach_title_rarity text,
  add column if not exists team_title text,
  add column if not exists team_title_rarity text,
  add column if not exists avatar_path text,
  add column if not exists team_logo_path text;

create table if not exists public.online_career_records (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  record_type text not null check (record_type in (
    'biggest_win',
    'biggest_loss',
    'top_scorer',
    'top_assistant',
    'winning_streak',
    'losing_streak',
    'highest_scoring_match'
  )),
  metric_value bigint not null check (metric_value >= 0 and metric_value <= 1000000000),
  record_snapshot jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint online_career_records_owner_type_unique unique (owner_user_id, record_type)
);

create index if not exists online_career_records_type_metric_idx
  on public.online_career_records (record_type, metric_value desc, recorded_at asc);

alter table public.online_career_records enable row level security;
-- No direct client policies: reads/writes are mediated by the authenticated career-api edge function.

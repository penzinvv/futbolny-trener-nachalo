create table if not exists public.coach_chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  coach_name text not null check (char_length(btrim(coach_name)) between 1 and 40),
  team_name text not null check (char_length(btrim(team_name)) between 1 and 60),
  message text not null check (char_length(btrim(message)) between 1 and 300),
  created_at timestamptz not null default now()
);
create index if not exists coach_chat_messages_created_id_idx on public.coach_chat_messages (id desc);
alter table public.coach_chat_messages enable row level security;
revoke all on public.coach_chat_messages from anon, authenticated;
grant select, insert on public.coach_chat_messages to authenticated;
grant usage, select on sequence public.coach_chat_messages_id_seq to authenticated;
drop policy if exists "Authenticated users can read coach chat" on public.coach_chat_messages;
create policy "Authenticated users can read coach chat" on public.coach_chat_messages for select to authenticated using (true);
drop policy if exists "Users can send coach chat messages as themselves" on public.coach_chat_messages;
create policy "Users can send coach chat messages as themselves" on public.coach_chat_messages for insert to authenticated with check (auth.uid() = user_id and char_length(btrim(message)) between 1 and 300);
